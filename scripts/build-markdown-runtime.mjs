#!/usr/bin/env node
/* Build crates/server/assets/runtime/markdown.js — the upstream markdown stack
 * (micromark/mdast + GFM + math/KaTeX + shiki + footnotes + incremental
 * streaming) as a classic-script IIFE that re-publishes `MarkdownText` on the
 * shared host runtime's `@deepseek-ai/dsh-client-ui-primitives` module.
 *
 * Why a build step: the reference renderer is an ESM package with external
 * React and a whole mdast/shiki/KaTeX dependency tree. The host page loads one
 * concatenated classic script (see crates/server/src/lib.rs `shared_runtime`),
 * so the tree has to be pre-bundled here and the React bindings aliased to the
 * shared instances. Nothing is eval'd and no ESM import survives in the output.
 *
 * Sources are pinned: scripts/markdown-runtime/pins.json holds the exact
 * version of every package in the install tree (used as `overrides`), so a
 * rebuild resolves the same graph and produces the same bytes.
 *
 * The install tree lives in target/markdown-runtime (gitignored), never in the
 * repository. Network access is needed only for the first install.
 *
 * Usage:
 *   node scripts/build-markdown-runtime.mjs          # build + refresh checksums
 *   node scripts/build-markdown-runtime.mjs --check  # verify the committed bytes
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");
const SOURCE_DIR = join(SCRIPT_DIR, "markdown-runtime");
const OUT_FILE = join(REPO_ROOT, "crates", "server", "assets", "runtime", "markdown.js");
const CHECKSUMS = join(REPO_ROOT, "crates", "server", "assets", "runtime", "checksums.txt");
const BUILD_DIR =
  process.env.DSHR_MARKDOWN_BUILD_DIR || join(REPO_ROOT, "target", "markdown-runtime");
const CHECK_ONLY = process.argv.includes("--check");

/* Packages the bundle imports directly. Everything else is pulled in through
 * their dependency ranges and pinned by pins.json `overrides`. */
const DIRECT = [
  "@deepseek-ai/dsh-client-ui-primitives",
  "@shikijs/langs",
  "anser",
  "clsx",
  "esbuild",
  "katex",
  "mdast-util-from-markdown",
  "mdast-util-gfm",
  "mdast-util-math",
  "micromark-core-commonmark",
  "micromark-extension-gfm",
  "micromark-extension-math",
  "micromark-factory-space",
  "micromark-util-character",
  "micromark-util-classify-character",
  "micromark-util-sanitize-uri",
  "micromark-util-symbol",
  "micromark-util-types",
  "react",
  "react-dom",
  "shiki",
];

/* Only these shiki grammars boot-load (same allowlist as the reference
 * highlighter). The reference lazily imports the read-card extension set; the
 * shim resolves those to an empty grammar so ~1.6 MB of never-used grammars
 * stays out of the artifact (such fences render as plain code). */
const BOOT_LANGS = new Set(["typescript", "shellscript", "json"]);

const BANNER = `/*! dshr shared runtime — upstream markdown stack (round 103, C2.7).
 * Generated by scripts/build-markdown-runtime.mjs — do not edit by hand.
 * Renderer: @deepseek-ai/dsh-client-ui-primitives (BSD-3-Clause) over
 * micromark/mdast + GFM + math (MIT), shiki (MIT), KaTeX (MIT).
 * Concatenated after primitives.js; overrides MarkdownText in the module table.
 * React/ReactDOM/jsx-runtime are external and bind to the shared host instances.
 */`;

function fail(message) {
  console.error(`build-markdown-runtime: ${message}`);
  process.exit(1);
}

function readPins() {
  return JSON.parse(readFileSync(join(SOURCE_DIR, "pins.json"), "utf8"));
}

/** `npm` from the PATH; the workspace needs no global esbuild. */
function npmCommand() {
  return process.platform === "win32" ? "npm.cmd" : "npm";
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { stdio: "inherit", ...options });
  if (result.error) fail(`${command} failed to start: ${result.error.message}`);
  if (result.status !== 0) fail(`${command} exited with ${result.status}`);
}

function installedVersion(name) {
  const manifest = join(BUILD_DIR, "node_modules", name, "package.json");
  if (!existsSync(manifest)) return null;
  return JSON.parse(readFileSync(manifest, "utf8")).version;
}

function requireInstalledVersion(name) {
  const version = installedVersion(name);
  if (version === null) fail(`missing installed package ${name}`);
  return version;
}

/* The install tree is reused across runs (and offline) when it still matches
 * the pins manifest; a pins edit changes the marker hash and re-installs. */
function pinsHash(pins) {
  return createHash("sha256").update(JSON.stringify(pins)).digest("hex");
}

function treeIsReady(pins, hash) {
  const marker = join(BUILD_DIR, ".dshr-pins.json");
  if (!existsSync(marker)) return false;
  let recorded;
  try {
    recorded = JSON.parse(readFileSync(marker, "utf8")).hash;
  } catch {
    return false;
  }
  if (recorded !== hash) return false;
  if (!existsSync(join(BUILD_DIR, "node_modules", "esbuild", "lib", "main.js"))) return false;
  return DIRECT.every((name) => installedVersion(name) === pins[name]);
}

/** The install tree's package.json: exact direct deps + exact overrides. */
function writeBuildManifest(pins) {
  const dependencies = {};
  for (const name of [...DIRECT].sort()) {
    if (pins[name] === undefined) fail(`pins.json has no version for direct dependency ${name}`);
    dependencies[name] = pins[name];
  }
  const manifest = {
    name: "dshr-markdown-runtime-build",
    private: true,
    description: "Install tree for crates/server/assets/runtime/markdown.js (gitignored, not shipped)",
    type: "module",
    dependencies,
    overrides: pins,
  };
  writeFileSync(join(BUILD_DIR, "package.json"), JSON.stringify(manifest, null, 2) + "\n");
}

function prepareTree(pins) {
  mkdirSync(BUILD_DIR, { recursive: true });
  writeBuildManifest(pins);
  for (const file of ["entry.js"]) {
    copyFileSync(join(SOURCE_DIR, file), join(BUILD_DIR, file));
  }
  mkdirSync(join(BUILD_DIR, "shims"), { recursive: true });
  for (const file of ["react.cjs", "react-dom.cjs", "jsx-runtime.cjs"]) {
    copyFileSync(join(SOURCE_DIR, "shims", file), join(BUILD_DIR, "shims", file));
  }
  const hash = pinsHash(pins);
  if (treeIsReady(pins, hash)) {
    console.log(`build-markdown-runtime: reusing install tree ${BUILD_DIR} (pins match)`);
    return;
  }
  console.log(`build-markdown-runtime: install tree ${BUILD_DIR}`);
  run(npmCommand(), ["install", "--no-audit", "--no-fund", "--ignore-scripts", "--loglevel=error"], {
    cwd: BUILD_DIR,
  });
  writeFileSync(join(BUILD_DIR, ".dshr-pins.json"), JSON.stringify({ hash }, null, 2) + "\n");
}

/** React is never bundled: these aliases resolve to shims over the host table. */
function aliasPlugin() {
  const shim = (name) => resolve(BUILD_DIR, "shims", name);
  return {
    name: "dshr-markdown-aliases",
    setup(build) {
      build.onResolve({ filter: /^react$/ }, () => ({ path: shim("react.cjs") }));
      build.onResolve({ filter: /^react-dom$/ }, () => ({ path: shim("react-dom.cjs") }));
      build.onResolve({ filter: /^react\/jsx-runtime$/ }, () => ({ path: shim("jsx-runtime.cjs") }));
      build.onResolve({ filter: /^react\/jsx-dev-runtime$/ }, () => ({ path: shim("jsx-runtime.cjs") }));
    },
  };
}

/** The reference's lazy grammar imports become empty grammars (see BOOT_LANGS). */
function lazyGrammarPlugin() {
  const PREFIX = "@shikijs/langs/";
  return {
    name: "dshr-markdown-lazy-grammars",
    setup(build) {
      build.onResolve({ filter: /^@shikijs\/langs\// }, (args) => {
        const name = args.path.slice(PREFIX.length);
        if (BOOT_LANGS.has(name)) return null;
        return { path: name, namespace: "dshr-lazy-grammar" };
      });
      build.onLoad({ filter: /.*/, namespace: "dshr-lazy-grammar" }, () => ({
        contents: "export default [];",
        loader: "js",
      }));
    },
  };
}

function meta() {
  return {
    upstream: `@deepseek-ai/dsh-client-ui-primitives@${requireInstalledVersion("@deepseek-ai/dsh-client-ui-primitives")}`,
    upstreamVersion: requireInstalledVersion("@deepseek-ai/dsh-client-ui-primitives"),
    stack: "micromark/mdast + GFM + math + shiki + KaTeX + footnotes + incremental streaming",
    shiki: requireInstalledVersion("shiki"),
    katex: requireInstalledVersion("katex"),
    esbuild: requireInstalledVersion("esbuild"),
    lang: [...BOOT_LANGS],
    react: "external: window.React / window.ReactDOM / window.__DSHR_MODULES__['react/jsx-runtime']",
  };
}

async function bundle(pins) {
  const requireFromHere = createRequire(import.meta.url);
  let esbuild;
  try {
    esbuild = requireFromHere(resolve(BUILD_DIR, "node_modules", "esbuild", "lib", "main.js"));
  } catch (error) {
    fail(`esbuild is unavailable in ${BUILD_DIR}: ${error.message}`);
  }
  const result = await esbuild.build({
    absWorkingDir: BUILD_DIR,
    entryPoints: ["entry.js"],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["chrome100", "safari15"],
    minify: true,
    legalComments: "none",
    loader: { ".css": "text" },
    define: {
      "process.env.NODE_ENV": '"production"',
      __DSHR_MARKDOWN_META__: JSON.stringify(meta()),
    },
    banner: { js: BANNER },
    plugins: [aliasPlugin(), lazyGrammarPlugin()],
    logLevel: "warning",
  });
  return Buffer.from(result.outputFiles[0].contents);
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function refreshChecksums(bytes) {
  const hash = sha256(bytes);
  const name = "markdown.js";
  const lines = readFileSync(CHECKSUMS, "utf8")
    .split("\n")
    .filter((line) => line.trim() !== "" && !line.trimEnd().endsWith(`  ${name}`));
  lines.push(`${hash}  ${name}`);
  writeFileSync(CHECKSUMS, lines.join("\n") + "\n");
  return hash;
}

const pins = readPins();
prepareTree(pins);
const bytes = await bundle(pins);
const hash = sha256(bytes);

if (CHECK_ONLY) {
  if (!existsSync(OUT_FILE)) fail(`${OUT_FILE} is missing; run without --check`);
  const committed = readFileSync(OUT_FILE);
  if (sha256(committed) !== hash) {
    fail(
      `artifact is stale: committed ${sha256(committed)} (${committed.length} bytes), ` +
        `rebuild gives ${hash} (${bytes.length} bytes)`,
    );
  }
  console.log(`build-markdown-runtime: up to date (${bytes.length} bytes, sha256 ${hash})`);
} else {
  writeFileSync(OUT_FILE, bytes); // checksums.txt refresh happens below
  const refreshed = refreshChecksums(bytes);
  console.log(
    `build-markdown-runtime: wrote ${OUT_FILE} (${bytes.length} bytes, sha256 ${refreshed})`,
  );
  console.log(`build-markdown-runtime: refreshed ${CHECKSUMS}`);
}
